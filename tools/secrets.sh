#!/bin/zsh
# Writes Broadcast/APNsKey.swift (gitignored) from the APNs key in ~/.appstoreconnect/apns, so the broadcast
# extension can push Island updates. The key never goes into git. Run by phone.sh and testflight.sh.
# Set CUT_APNS_P8 to use a particular key file (e.g. a Cut-only key).
set -euo pipefail
cd "$(dirname "$0")/.."
p8=${CUT_APNS_P8:-$(ls ~/.appstoreconnect/apns/AuthKey_*.p8 | head -1)}
id=${${p8:t:r}#AuthKey_}
{
  print "// Generated by tools/secrets.sh. Not in git."
  print "enum APNsKey {"
  print "    static let id = \"$id\""
  print "    static let team = \"8QPPD49JQ5\""
  print "    static let pem = \"\"\""
  cat $p8
  [[ -z $(tail -c1 $p8) ]] || print  # the key file may not end in a newline
  print "\"\"\""
  print "}"
} > Broadcast/APNsKey.swift
